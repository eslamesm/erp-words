#!/usr/bin/env node
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_PATH = join(ROOT, "src", "data", "jobPathRouteIndex.generated.ts");
const FORMAT_VERSION = 1;
const SOURCE_FILES = [
  "jobPaths.ts",
  "jobPathsAccountant.ts",
  "jobPathsProcurement.ts",
  "jobPathsManufacturing.ts",
  "jobPathsWarehouse.ts",
];
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const checkOnly = process.argv.includes("--check");

function fail(message) {
  console.error(`[route-index] ${message}`);
  process.exitCode = 1;
}

function readSources() {
  const sources = new Map();
  for (const name of SOURCE_FILES) {
    const filePath = join(ROOT, "src", "data", name);
    if (!existsSync(filePath)) {
      throw new Error(`missing authoritative source file: src/data/${name}`);
    }
    sources.set(name, readFileSync(filePath));
  }
  return sources;
}

function computeSourceHash(sources) {
  const hash = createHash("sha256");
  hash.update(`format:${FORMAT_VERSION}\n`);
  for (const name of SOURCE_FILES) {
    hash.update(`file:${name}\n`);
    hash.update(sources.get(name));
    hash.update("\n");
  }
  return hash.digest("hex");
}

function loadJobPaths(sources, tempDir) {
  const requireFromRoot = createRequire(import.meta.url);
  for (const [name, source] of sources) {
    const { outputText } = ts.transpileModule(source.toString("utf8"), {
      fileName: name,
      compilerOptions: {
        module: ts.ModuleKind.CommonJS,
        target: ts.ScriptTarget.ES2022,
        esModuleInterop: true,
        isolatedModules: true,
      },
    });
    if (outputText.includes('require("@/') || outputText.includes("require('@/")) {
      throw new Error(`unexpected runtime alias import after transpiling src/data/${name}`);
    }
    writeFileSync(join(tempDir, name.replace(/\.ts$/, ".js")), outputText, "utf8");
  }
  const jobPathsModule = requireFromRoot(join(tempDir, "jobPaths.js"));
  if (!Array.isArray(jobPathsModule.JOB_PATHS)) {
    throw new Error("JOB_PATHS is missing or is not an array");
  }
  return jobPathsModule.JOB_PATHS;
}

function validatePath(path, index) {
  if (!path || typeof path.slug !== "string" || !SLUG_PATTERN.test(path.slug)) {
    throw new Error(`invalid job path slug at index ${index}`);
  }
  if (path.status !== "ready" && path.status !== "planned") {
    throw new Error(`invalid status for job path "${path.slug}"`);
  }
  if (!Array.isArray(path.lessons) || path.lessons.length === 0) {
    throw new Error(`job path "${path.slug}" has no lessons`);
  }
  const seen = new Set();
  for (const lesson of path.lessons) {
    if (!lesson || typeof lesson.slug !== "string" || !SLUG_PATTERN.test(lesson.slug)) {
      throw new Error(`invalid lesson slug in job path "${path.slug}"`);
    }
    if (seen.has(lesson.slug)) {
      throw new Error(`duplicate lesson slug "${lesson.slug}" in job path "${path.slug}"`);
    }
    seen.add(lesson.slug);
  }
}

function buildIndex(jobPaths, sourceHash) {
  const ready = new Map();
  const seenSlugs = new Set();
  jobPaths.forEach((path, index) => {
    validatePath(path, index);
    if (seenSlugs.has(path.slug)) {
      throw new Error(`duplicate job path slug "${path.slug}"`);
    }
    seenSlugs.add(path.slug);
    if (path.status === "ready") {
      ready.set(path.slug, path.lessons.map((lesson) => lesson.slug));
    }
  });
  const ordered = {};
  for (const slug of [...ready.keys()].sort()) {
    ordered[slug] = ready.get(slug);
  }
  if (Object.keys(ordered).length === 0) {
    throw new Error("no ready job paths found; refusing to emit an empty route index");
  }
  return { version: FORMAT_VERSION, sourceHash, ready: ordered };
}

function serialize(index) {
  const lines = [
    "// AUTO-GENERATED by scripts/generate-job-route-index.mjs - DO NOT EDIT.",
    "// Regenerate with: npm run gen:route-index",
    "export const JOB_ROUTE_INDEX = {",
    `  version: ${index.version},`,
    `  sourceHash: "${index.sourceHash}",`,
    "  ready: {",
  ];
  for (const [slug, lessons] of Object.entries(index.ready)) {
    lines.push(`    "${slug}": [`);
    for (const lesson of lessons) {
      lines.push(`      "${lesson}",`);
    }
    lines.push("    ],");
  }
  lines.push("  },", "} as const;", "");
  return lines.join("\n");
}

function writeAtomically(contents) {
  const tempFile = `${OUTPUT_PATH}.tmp-${process.pid}`;
  try {
    writeFileSync(tempFile, contents, "utf8");
    renameSync(tempFile, OUTPUT_PATH);
  } catch (error) {
    rmSync(tempFile, { force: true });
    throw error;
  }
}

function main() {
  let tempDir;
  try {
    const sources = readSources();
    const sourceHash = computeSourceHash(sources);
    tempDir = mkdtempSync(join(tmpdir(), "job-route-index-"));
    const jobPaths = loadJobPaths(sources, tempDir);
    const index = buildIndex(jobPaths, sourceHash);
    const contents = serialize(index);
    const existing = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, "utf8") : null;
    const readyCount = Object.keys(index.ready).length;
    const lessonCount = Object.values(index.ready).reduce(
      (total, lessons) => total + lessons.length,
      0
    );

    if (checkOnly) {
      if (existing === null) {
        fail("generated route index is missing; run npm run gen:route-index");
        return;
      }
      if (existing !== contents) {
        fail("generated route index is stale; run npm run gen:route-index");
        return;
      }
      console.log(
        `[route-index] up to date (${readyCount} ready paths, ${lessonCount} lessons)`
      );
      return;
    }

    if (existing === contents) {
      console.log(
        `[route-index] up to date, nothing written (${readyCount} ready paths, ${lessonCount} lessons)`
      );
      return;
    }
    writeAtomically(contents);
    console.log(
      `[route-index] wrote src/data/jobPathRouteIndex.generated.ts (${readyCount} ready paths, ${lessonCount} lessons)`
    );
  } catch (error) {
    fail(error instanceof Error ? error.message : String(error));
  } finally {
    if (tempDir) {
      rmSync(tempDir, { recursive: true, force: true });
    }
  }
}

main();
