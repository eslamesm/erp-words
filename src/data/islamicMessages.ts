export function pickIslamicMessage(seed?: number): IslamicMessage {
  const rng = seed === undefined ? Math.random() : ((seed * 9301 + 49297) % 233280) / 233280;
  const index = Math.floor(rng * ISLAMIC_MESSAGES.length);
  return ISLAMIC_MESSAGES[index];
}
