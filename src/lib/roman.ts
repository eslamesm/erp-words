// تحويل الكلمة العربية إلى حروف لاتينية (كتابة صوتية مبسطة) لمساعدة التعلّم.

const AR_TO_ROM: Record<string, string> = {
  "أ": "a", "إ": "e", "آ": "aa", "ا": "a", "ب": "b", "ت": "t", "ث": "th",
  "ج": "j", "ح": "h", "خ": "kh", "د": "d", "ذ": "dh", "ر": "r", "ز": "z",
  "س": "s", "ش": "sh", "ص": "s", "ض": "d", "ط": "t", "ظ": "z", "ع": "'",
  "غ": "gh", "ف": "f", "ق": "q", "ك": "k", "ل": "l", "م": "m", "ن": "n",
  "ه": "h", "و": "w", "ي": "y", "ؤ": "w", "ئ": "'i", "ء": "'", "ة": "ah",
  "ى": "a", "پ": "p", "چ": "ch", "ڤ": "v", "گ": "g",
  "َ": "a", "ُ": "u", "ِ": "i", "ً": "an", "ٌ": "un", "ٍ": "in",
  "ّ": "", "ْ": "", "ـ": "",
};

export function romanize(text: string): string {
  if (!text) return "";
  let out = text
    .split("")
    .map((ch) => AR_TO_ROM[ch] ?? (ch === " " ? " " : ch))
    .join("");
  // ضمّ أدوات التعريف: "ال" تُكتب "al-" وكلمة "وال" => "wal-"
  out = out.replace(/\b(wa)?al-(?=[a-z])/g, (m) => (m.startsWith("wa") ? "wal-" : "al-"));
  // تنظيف الأحرف المتكررة والتشكيل الزائد
  out = out.replace(/\s+/g, " ").trim();
  // حذف الفواصل المتتالية الناتجة عن الهمزات
  out = out.replace(/'{2,}/g, "'");
  return out;
}